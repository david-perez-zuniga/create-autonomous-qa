import fs from "node:fs";
import path from "node:path";

import type { PackageManagerConfig } from "../constants/package-managers.js";
import { MESSAGES } from "../constants/messages.js";
import { CliError } from "../errors/cli-error.js";

export interface PackageJsonInput {
  packageJsonPath: string;
  packageName: string;
  packageManager: PackageManagerConfig;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

function isPermissionError(error: unknown): boolean {
  return (
    typeof error === "object" &&
    error !== null &&
    "code" in error &&
    ((error as NodeJS.ErrnoException).code === "EACCES" ||
      (error as NodeJS.ErrnoException).code === "EPERM")
  );
}

function configError(filePath: string, error: unknown): never {
  if (isPermissionError(error)) {
    throw new CliError("E_PERMISSION", MESSAGES.errors.permission(filePath));
  }

  const detail = error instanceof Error ? error.message : String(error);
  throw new CliError(
    "E_CONFIG_FAILED",
    MESSAGES.errors.configFailed(filePath, detail)
  );
}

export function updatePackageJson(input: PackageJsonInput): void {
  const { packageJsonPath, packageName, packageManager } = input;

  let parsed: unknown;

  try {
    parsed = JSON.parse(fs.readFileSync(packageJsonPath, "utf8"));
  } catch (error) {
    configError(path.basename(packageJsonPath), error);
  }

  if (!isRecord(parsed)) {
    configError(
      path.basename(packageJsonPath),
      new Error("package.json must contain a JSON object")
    );
  }

  parsed["name"] = packageName;
  parsed["version"] = "0.1.0";
  parsed["private"] = true;
  parsed["description"] =
    "Autonomous QA project generated by create-autonomous-qa";
  parsed["type"] = "module";
  parsed["packageManager"] = packageManager.packageManager;

  const currentScripts = isRecord(parsed["scripts"]) ? parsed["scripts"] : {};
  currentScripts["test"] ??= "playwright test";
  currentScripts["test:ui"] ??= "playwright test --ui";
  currentScripts["test:headed"] ??= "playwright test --headed";
  currentScripts["test:debug"] ??= "playwright test --debug";
  currentScripts["report"] ??= "playwright show-report";
  parsed["scripts"] = currentScripts;

  try {
    fs.writeFileSync(
      packageJsonPath,
      `${JSON.stringify(parsed, null, 2)}\n`,
      "utf8"
    );
  } catch (error) {
    configError(path.basename(packageJsonPath), error);
  }
}
